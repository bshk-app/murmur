#!/usr/bin/env node
// Rebuild the baseline from the same pinned artifacts the downloader consumes.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../..');
const hash = value => createHash('sha256').update(value).digest('hex');
const sources = ['TranslationQualityDigests.swift', 'FinnishQualityDigests.swift', 'EuropeanQualityDigests.swift'];
const tags = ['', ...JSON.parse(fs.readFileSync(path.join(root, 'Engine/Translation/Catalog/eu-opus-sources.json'))).map(x => x.target_tag), '>>rus<<'];
const byHash = new Map(tags.filter(Boolean).map(tag => [hash(tag + '\n'), tag]));
const bindings = [];
for (const name of sources) {
  const source = fs.readFileSync(path.join(root, 'Engine/Translation/Sources/MurmurTranslation', name), 'utf8');
  for (const [, pair, body] of source.matchAll(/"([a-z]{4})": Entry\(files: \[([\s\S]*?)\]\)/g)) {
    const files = [...body.matchAll(/File\(name:\s*"([^"]+)",\s*sha256:\s*"([a-f0-9]{64})",\s*(?:\/\/[^\n]*\n\s*)*bytes:\s*([\d_]+)\)/g)].map(([, name, sha256, bytes]) => ({name, sha256, bytes: Number(bytes.replaceAll('_', ''))}));
    if (!['model.bin', 'config.json', 'source.spm', 'target.spm'].every(name => files.some(f => f.name === name))) throw Error(`Incomplete pins: ${pair}`);
    const tagFile = files.find(f => f.name === 'target_tag.txt');
    const targetTag = tagFile ? byHash.get(tagFile.sha256) : '';
    if (targetTag === undefined) throw Error(`Unknown pinned target tag: ${pair}`);
    // Include vocabularies and tokenizers, not just model.bin, in model identity.
    const modelID = 'opus-' + hash(files.filter(f => f.name !== 'target_tag.txt').sort((a,b) => a.name.localeCompare(b.name)).map(f => `${f.name}:${f.sha256}`).join('\n'));
    bindings.push({pair: {source: pair.slice(0,2), target: pair.slice(2)}, modelID, directoryName: `ct2-${pair}`, targetTag,
      decoding: {beamSize: 1, maxSourcePieces: 200, maxDecodingLength: 512, lengthPenalty: 1, computeType: 'int8'}, files});
  }
}
if (bindings.length !== 66 || new Set(bindings.map(b => b.directoryName)).size !== 66) throw Error('Expected 66 unique baseline directions');
bindings.sort((a,b) => a.directoryName.localeCompare(b.directoryName));
const version = 'baseline-' + hash(JSON.stringify(bindings)).slice(0,16);
const rows = bindings.map(b => `        .init(pair: .init(source: "${b.pair.source}", target: "${b.pair.target}"), modelID: "${b.modelID}", directoryName: "${b.directoryName}", targetTag: "${b.targetTag}")`);
const swift = `// Generated by Engine/Translation/Scripts/generate-quality-baseline.mjs.\n// Baseline compatibility is not a claim of quality qualification.\nextension TranslationProfileCatalog {\n    public static let baseline = try! TranslationProfileCatalog(\n        version: "${version}", bindings: [\n${rows.join(',\n')}\n    ])\n}\n`;
const manifest = JSON.stringify({schemaVersion: 1, version, status: 'baseline', runtime: 'CTranslate2 4.8.2 CPU, one thread', bindings}, null, 2) + '\n';
const outputs = [[path.join(root, 'Engine/Core/Sources/MurmurCore/BaselineTranslationProfiles.swift'), swift], [path.join(root, 'Engine/Translation/Catalog/quality-baseline.json'), manifest]];
for (const [file, content] of outputs) {
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(file, 'utf8') !== content) throw Error(`Stale generated baseline: ${file}`);
  } else fs.writeFileSync(file, content);
}
console.log(`${version}: ${bindings.length} bindings, ${new Set(bindings.map(b => b.modelID)).size} distinct model assets`);
